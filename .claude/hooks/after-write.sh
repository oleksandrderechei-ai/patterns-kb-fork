      ;;
    docs/data/allow/prerequisites.json)
      note "docs/data/allow/prerequisites.json is the prerequisites gate's orphan allowlist, matched against a record's route; an entry needs a reason and must excuse something, and json-sanity holds its source header. Run: make gate G=check-prerequisites && make gate G=check-json"
      ;;
    docs/data/prerequisites.json)
