# ---------------------------------------------------------------------------
# 4. A skill, an agent or a rule. The harness-shape and harness-routes gates
#    hold its shape and its links. A malformed SKILL.md fails to register
#    without a word, so the edit names both while it is fresh.
# ---------------------------------------------------------------------------
check_harness() {
  case "$rel" in
    .claude/worktrees/*) ;;
    .claude/*.md)
      note "$rel is read by the harness-shape gate, which holds its shape, and by the harness-routes gate, which holds its links. Run: make gate G=check-harness && make gate G=check-harness-routes"
      ;;
  esac
}

# ---------------------------------------------------------------------------
# 5. A context layer. The budgets and the margin are read out of the layer
#    gate at run time, so this hook holds no copy of them; when it cannot read
#    them, it says nothing. A nested layer is measured in lines, by the gate.
# ---------------------------------------------------------------------------
gate_const() { # <name> -> the value `export const <name> = N;` holds in the layer gate
  sed -n "s/^export const $1 = \([0-9][0-9]*\);.*/\1/p" "$root/tools/src/gates/check-claude-md.ts" 2>/dev/null | head -n 1
}

check_layer() {
  local budget margin words
  case "$rel" in
    CLAUDE.md) budget="$(gate_const ROOT_BUDGET)" ;;
    */*/CLAUDE.md) return 0 ;;
    */CLAUDE.md) budget="$(gate_const LAYER_BUDGET)" ;;
    *) return 0 ;;
  esac
  margin="$(gate_const ADVISORY_MARGIN)"
  [ -n "$budget" ] && [ -n "$margin" ] || return 0

  words="$(wc -w < "$abs" 2>/dev/null | tr -d ' ')"
  [ -n "$words" ] || return 0
  # From the margin below the budget, the margin included (hooks-C4).
  if [ "$words" -gt "$budget" ]; then
    note "$rel is now $words words, over its $budget budget, so make gate G=check-claude-md will fail. Move a line to its single source and leave a link (docs/concepts/context-layering.md)."
  elif [ "$words" -ge $((budget - margin)) ]; then
    note "$rel is now $words/$budget words: the next fact added here must displace one to its single source. Check it with: make gate G=check-claude-md"
  fi
}

check_stamped
check_output
check_data
check_harness
check_layer

[ -n "$NOTES" ] || exit 0

# additionalContext reaches the session; systemMessage reaches the person at
# the keyboard. Both, with the same text, because either alone leaves one out.
jq -nc --arg n "$NOTES" \
  '{hookSpecificOutput:{hookEventName:"PostToolUse",additionalContext:$n},systemMessage:$n}' 2>/dev/null
exit 0
