#!/usr/bin/env bash
# PostToolUse(Edit|Write|MultiEdit): say what the edit just committed you to,
# while you still remember writing it (spec: kb.harness.hooks, advisory).
#
# Some mistakes are silent at the keyboard and loud in `make validate` later,
# when re-earning the context costs more than the fix:
#
#   1. hand-editing a stamped file — its generator's `--check` reports the drift;
#   2. editing a file in an ignored output folder — the next run replaces it;
#   3. editing a data file without the command that reads it;
#   4. editing a skill, an agent or a rule without the two gates that hold
#      their shape and their links;
#   5. pushing a context layer to within ADVISORY_MARGIN words of its budget,
#      or past it (docs/concepts/context-layering.md).
#
# None is a reason to stop: each is legitimate work one command away from
# right. So this hook only advises. It never blocks, never writes, never
# reaches the network, and always exits 0. It reads the edited path off the
# payload, prints what that path owes as one JSON object whose two note fields
# carry the same text, and is otherwise silent: on a hand-written page, a
# program source, a missing file, a path outside the project and any payload
# it cannot read.
#
# Adding a case: a function that calls `note`, called at the bottom. Name the
# command to run, not the concept behind it.
set -uo pipefail

payload="$(cat 2>/dev/null || true)"
command -v jq >/dev/null 2>&1 || exit 0

file="$(printf '%s' "$payload" |
  jq -r 'if type == "object" then (.tool_input.file_path // "") else "" end' 2>/dev/null || true)"
[ -n "$file" ] || exit 0

root="${CLAUDE_PROJECT_DIR:-$(git rev-parse --show-toplevel 2>/dev/null || true)}"
[ -n "$root" ] || exit 0

# Repo-relative, so every note reads like a path in the tree. An edit outside
# the checkout is none of this hook's business.
case "$file" in
  "$root"/*) rel="${file#"$root"/}" ;;
  /*) exit 0 ;;
  *) rel="$file" ;;
esac
abs="$root/$rel"
[ -f "$abs" ] || exit 0

NOTES=""
note() {
  NOTES="${NOTES}${NOTES:+
}[after-write] $1"
}

# ---------------------------------------------------------------------------
# 1. A stamped file. The generator is read off the file's own stamp, so a
#    generator added tomorrow is covered tomorrow. The whole file is searched,
#    since a stamp below frontmatter is still a stamp, but only a line that is
#    the stamp alone, outside a fence, counts: a page quoting the stamp text in
#    prose or in an example is still hand-written. Only a whole-file stamp
#    counts, too: a hand-written page holding a generated block (the triage
#    page) stamps only that block, and the block's freshness gate owns it. The
#    repair command is the `fix` of the registry row that runs the generator
#    with `--check`.
# ---------------------------------------------------------------------------
check_stamped() {
  local stamp gen src fix
  # The prerequisite reference page is built from the relations file and the
  # pages' titles and descriptions at once, so the note names both.
  case "$rel" in
    docs/reference/prerequisites.md)
      note "docs/reference/prerequisites.md is GENERATED by tools/src/gen/gen-prerequisites.ts from docs/data/relations.json and the pages' titles and descriptions; the prerequisites-fresh gate fails a hand edit. Edit docs/data/relations.json (node scripts/kb.mjs link or unlink write whole edges), or a title or description on its page, instead, then run: make gen && make gate G=check-prerequisites"
      return 0
      ;;
  esac
  stamp="$(awk '
    /^[[:space:]]*(```|~~~)/ { fenced = !fenced; next }
    !fenced && /^[[:space:]]*(<!--|\/\/|#|\/\*)[[:space:]]*GENERATED by [^ ]+ from [^ ]+\. Do not edit this file\.[[:space:]]*(-->|\*\/)?[[:space:]]*$/ { print; exit }
  ' "$abs" 2>/dev/null || true)"
  [ -n "$stamp" ] || return 0
  gen="$(printf '%s' "$stamp" | sed -E 's/.*GENERATED by ([^ ]+) from .*/\1/')"
  src="$(printf '%s' "$stamp" | sed -E 's/.*GENERATED by [^ ]+ from ([^ ]+)\. Do not edit this file\..*/\1/')"
  fix="$(jq -r --arg g "$gen --check" \
    'first(.gates[]? | select(((.wired // "") + " " + (.local_command // "")) | contains($g)) | .fix) // ""' \
    "$root/docs/data/gates.json" 2>/dev/null || true)"
  if [ -n "$fix" ]; then
    note "$rel is GENERATED by $gen from $src. Edit $src instead, then run: $fix"
  else
    note "$rel is GENERATED by $gen from $src. Edit the generator's source or $src instead, never this file."
  fi
}

# ---------------------------------------------------------------------------
# 2. An ignored output folder: the next run replaces whatever was edited.
# ---------------------------------------------------------------------------
check_output() {
  case "$rel" in
    tools/coverage/*)
      note "$rel is coverage output, rebuilt by \`make tools-test\` and never committed; your edit will not survive the next run. Run: make tools-test"
      ;;
    site/coverage/*)
      note "$rel is coverage output, rebuilt by \`make site-test\` and never committed; your edit will not survive the next run. Run: make site-test"
      ;;
    site/dist/* | site/.astro/* | site/node_modules/.astro/* | site/public/kb.js)
      note "$rel is output of the site build, never committed; the next build replaces it. Change the page under docs/, the site workspace or tools/src/site/ instead, then run: make site-build"
      ;;
    site/src/content/docs/map/*.mdx) # the map area's page, before the hub case that would claim an index.mdx
      note "$rel is a map page tools/src/site/gen-map-pages.ts writes on every site build from docs/data/site-structure.json, never committed. Change that generator or the components it places instead, then run: make site-build"
      ;;
    site/src/content/docs/*/*index.mdx) # a hub below the top folder; the top index.mdx is hand-written
      note "$rel is a hub tools/src/site/gen-site-hubs.ts writes on every site build from docs/data/site-structure.json and its pages' frontmatter, never committed. Change those instead, then run: make site-build"
      ;;
    site/src/content/docs/*.md)
      note "$rel is the copy tools/src/site/gen-site-docs.ts mirrors from docs/ on every site build, never committed. Change the page under docs/ instead, then run: make site-build"
      ;;
  esac
}

# ---------------------------------------------------------------------------
# 3. A data file. Each names what reads it and the command to run, written
#    out because the coupling is the fact worth knowing. Every file under docs/data/ needs its own case here; the suite
#    fails when one has none. Each of them also owes the json-sanity gate its
#    source header (version, updated, note), so each command ends with it.
# ---------------------------------------------------------------------------
check_data() {
  case "$rel" in
    docs/data/gates.json)
      note "docs/data/gates.json is read by tools/src/gen/gen-gates.ts (docs/reference/gates.md and the triage page's generated blocks), by the driver behind \`make validate\`, and by the gates-sync gate, which holds it to the Makefile, the workflow and the triage page; json-sanity holds its source header. Run: make gates && make gate G=check-gates-sync && make gate G=check-json"
      ;;
    docs/data/allow/test-colocation.json)
      note "docs/data/allow/test-colocation.json is the test-colocation gate's allowlist; an entry needs a reason and must excuse something, and json-sanity holds its source header. Run: make gate G=check-test-colocation && make gate G=check-json"
      ;;
    docs/data/allow/vocabulary.json)
      note "docs/data/allow/vocabulary.json is the vocabulary gate's allowlist: an entry excuses the banned phrasings in the files it matches, needs a reason, an owner and a since date (a banned phrasing is a failure, never a category), and must excuse something; json-sanity holds its source header. Run: make gate G=check-vocabulary && make gate G=check-json"
      ;;
    docs/data/allow/context-layers.json)
      note "docs/data/allow/context-layers.json is the context-layers gate's placement allowlist; an entry needs owner, since and reason, and must excuse something, and json-sanity holds its source header. Run: make gate G=check-claude-md && make gate G=check-json"
